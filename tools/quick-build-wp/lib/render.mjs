/**
 * tools/quick-build-wp/lib/render.mjs
 *
 * 把 buildPlan() 的计划渲染成一份可在 Linux（Debian/Ubuntu + 宝塔系 apt 环境）
 * 上直接执行的 bash 安装脚本。设计约束：
 *   - 幂等：每个安装动作都有「已存在则跳过」的守卫；
 *   - 支持 --dry-run：所有写操作统一走 _run / _write_conf 封装，dry-run 只打印；
 *   - 确定性：脚本内不写时间戳，同一份计划重复 emit 字节级一致；
 *   - 可配置变量全部带默认值，可用环境变量覆盖。
 *
 * 纯 Node 内置模块，零新增依赖。
 */

import { buildPlan } from './plan.mjs';

/**
 * 渲染安装脚本。
 * @param {{domain?:string, phpVersion?:string, wpVersion?:string, ssl?:boolean}} opts
 * @returns {string} bash 脚本文本（UTF-8，LF 换行）
 */
export function renderScript(opts = {}) {
  const plan = buildPlan(opts);
  const { domain, phpVersion, wpVersion, ssl } = plan.options;

  // 可选 SSL：计划里 ssl=true 时脚本默认开启，否则由 INSTALL_SSL 环境变量控制。
  const defaultSsl = ssl ? '1' : '0';

  const lines = [];
  const push = (line = '') => lines.push(line);

  push('#!/usr/bin/env bash');
  push('# AUTO-GENERATED by quick-build-wp (tools/quick-build-wp). Do not edit by hand.');
  push('# 用法: sudo bash install.sh [--dry-run]');
  push('set -euo pipefail');
  push();
  push('# ---- 可配置变量（全部带默认值，可用环境变量覆盖）----');
  push(`DOMAIN="\${DOMAIN:-${domain}}"`);
  push(`PHP_VERSION="\${PHP_VERSION:-${phpVersion}}"`);
  push(`WP_VERSION="\${WP_VERSION:-${wpVersion}}"`);
  push('DB_NAME="${DB_NAME:-wp_$(printf \'%s\' "${DOMAIN}" | tr \'.\' \'_\')}"');
  push('DB_USER="${DB_USER:-wp_user}"');
  push('DB_PASS="${DB_PASS:-ChangeMe_default_only_for_dry_run}"');
  push('WEB_ROOT="${WEB_ROOT:-/var/www/${DOMAIN}}"');
  push(`INSTALL_SSL="\${INSTALL_SSL:-${defaultSsl}}"`);
  push();
  push('# ---- 解析脚本自身参数 ----');
  push('DRY_RUN=0');
  push('for arg in "$@"; do');
  push('  case "${arg}" in');
  push('    --dry-run) DRY_RUN=1 ;;');
  push('    *) echo "unknown argument: ${arg}" >&2; exit 2 ;;');
  push('  esac');
  push('done');
  push();
  push('# 命令执行封装：dry-run 只打印不写盘；真实执行原样调用。');
  push('_run() {');
  push('  if [ "${DRY_RUN}" -eq 1 ]; then');
  push('    echo "[dry-run] $*"');
  push('  else');
  push('    "$@"');
  push('  fi');
  push('}');
  push();
  push('info() { echo "[*] $*"; }');
  push();
  push('# 写文件封装：dry-run 只打印目标路径；真实执行先建目录再用 heredoc 落盘。');
  push('_write_conf() {');
  push('  target="$1"');
  push('  if [ "${DRY_RUN}" -eq 1 ]; then');
  push('    echo "[dry-run] write ${target}"');
  push('  else');
  push('    mkdir -p "$(dirname "${target}")"');
  push('    cat > "${target}"');
  push('  fi');
  push('}');
  push();

  // 1. 环境自检
  push('# env-check — 1/8 环境自检');
  push('info "1/8 环境自检"');
  push('_run command -v curl');
  push('_run command -v tar');
  push();

  // 2. Nginx
  push('# install-nginx — 2/8 安装 Nginx（已存在则跳过）');
  push('info "2/8 安装 Nginx"');
  push('if command -v nginx >/dev/null 2>&1; then');
  push('  info "nginx 已存在，跳过"');
  push('else');
  push('  _run apt-get update');
  push('  _run apt-get install -y nginx');
  push('  _run systemctl enable nginx');
  push('  _run systemctl start nginx');
  push('fi');
  push();

  // 3. MySQL
  push('# install-mysql — 3/8 安装 MySQL（已存在则跳过）');
  push('info "3/8 安装 MySQL"');
  push('if command -v mysqld >/dev/null 2>&1 || dpkg -l mysql-server >/dev/null 2>&1; then');
  push('  info "mysql-server 已存在，跳过"');
  push('else');
  push('  _run apt-get install -y mysql-server');
  push('  _run systemctl enable mysql');
  push('  _run systemctl start mysql');
  push('fi');
  push();

  // 4. PHP
  push('# install-php — 4/8 安装 PHP（已存在对应 fpm 包则跳过）');
  push('info "4/8 安装 PHP ${PHP_VERSION}"');
  push('if dpkg -l "php${PHP_VERSION}-fpm" >/dev/null 2>&1; then');
  push('  info "php${PHP_VERSION}-fpm 已存在，跳过"');
  push('else');
  push('  _run apt-get install -y "php${PHP_VERSION}-fpm" "php${PHP_VERSION}-mysql" "php${PHP_VERSION}-cli"');
  push('  _run systemctl enable "php${PHP_VERSION}-fpm"');
  push('fi');
  push();

  // 5. 数据库与账号（CREATE IF NOT EXISTS 天然幂等）
  push('# create-db — 5/8 创建数据库与专用账号');
  push('info "5/8 创建数据库与专用账号"');
  push('_run mysql -e "CREATE DATABASE IF NOT EXISTS \\`${DB_NAME}\\` CHARACTER SET utf8mb4;"');
  push('_run mysql -e "CREATE USER IF NOT EXISTS \'${DB_USER}\'@\'localhost\' IDENTIFIED BY \'${DB_PASS}\';"');
  push('_run mysql -e "GRANT ALL PRIVILEGES ON \\`${DB_NAME}\\`.* TO \'${DB_USER}\'@\'localhost\';"');
  push('_run mysql -e "FLUSH PRIVILEGES;"');
  push();

  // 6. 下载 WordPress
  push('# download-wp — 6/8 下载并解压 WordPress（站点目录已有 wp-load.php 则跳过）');
  push('info "6/8 下载 WordPress"');
  push('if [ -f "${WEB_ROOT}/wp-load.php" ]; then');
  push('  info "WordPress 已存在，跳过"');
  push('else');
  push('  _run mkdir -p "${WEB_ROOT}"');
  push('  _run curl -fSL "https://wordpress.org/wordpress-${WP_VERSION}.tar.gz" -o /tmp/wordpress.tar.gz');
  push('  _run tar -xzf /tmp/wordpress.tar.gz -C "${WEB_ROOT}" --strip-components=1');
  push('  _run chown -R www-data:www-data "${WEB_ROOT}"');
  push('fi');
  push();

  // 7. Nginx 站点 + 伪静态
  push('# nginx-site — 7/8 写入站点 Nginx 配置与伪静态规则');
  push('info "7/8 站点配置与伪静态"');
  push('_write_conf "/etc/nginx/sites-available/${DOMAIN}.conf" <<NGINX_EOF');
  push('server {');
  push('    listen 80;');
  push('    server_name ${DOMAIN};');
  push('    root ${WEB_ROOT};');
  push('    index index.php index.html;');
  push();
  push('    # WordPress 伪静态：try_files 回退到 index.php');
  push('    location / {');
  push('        try_files \\$uri \\$uri/ /index.php?\\$args;');
  push('    }');
  push();
  push('    location ~ \\.php$ {');
  push('        include snippets/fastcgi-php.conf;');
  push('        fastcgi_pass unix:/run/php/php${PHP_VERSION}-fpm.sock;');
  push('    }');
  push();
  push('    location ~* \\.(env|git|htaccess)$ { deny all; }');
  push('}');
  push('NGINX_EOF');
  push('_run ln -sf "/etc/nginx/sites-available/${DOMAIN}.conf" "/etc/nginx/sites-enabled/${DOMAIN}.conf"');
  push('_run nginx -t');
  push('_run systemctl reload nginx');
  push();

  // 8. 可选 SSL
  push('# ssl — 8/8 可选：申请并配置 HTTPS 证书');
  push('if [ "${INSTALL_SSL}" -eq 1 ]; then');
  push('  info "8/8 配置 HTTPS"');
  push('  if command -v certbot >/dev/null 2>&1; then');
  push('    _run certbot --nginx -d "${DOMAIN}" --non-interactive --agree-tos --register-unsafely-without-email');
  push('  else');
  push('    _run apt-get install -y certbot python3-certbot-nginx');
  push('    _run certbot --nginx -d "${DOMAIN}" --non-interactive --agree-tos --register-unsafely-without-email');
  push('  fi');
  push('else');
  push('  info "8/8 跳过 HTTPS（INSTALL_SSL=1 启用）"');
  push('fi');
  push();
  push('info "完成：站点目录 ${WEB_ROOT}"');

  return lines.join('\n') + '\n';
}
