/**
 * tools/liudun-waf/lib/nginx.mjs
 *
 * 把 rules.json 等价翻译成一段 nginx 配置：
 *   - limit_req_zone 做 CC 限流；
 *   - geo 做 IP 黑白名单；
 *   - map $request_uri 做签名规则匹配，命中返回 403；
 *   - proxy_pass 回源上游。
 *
 * 纯字符串渲染，不执行 nginx；零新增依赖。
 */

import { compileRules } from './waf.mjs';

/**
 * 渲染 nginx 配置。
 * @param {{listen?:number|string, upstream:string, rules:object}} opts
 * @returns {string}
 */
export function renderNginx({ listen = 8801, upstream, rules }) {
  const c = compileRules(rules);
  const ratePerSec = Math.max(0.1, Math.round((c.rateLimit.max / (c.rateLimit.windowMs / 1000)) * 10) / 10);

  const lines = [];
  const push = (line = '') => lines.push(line);

  push('# AUTO-GENERATED by liudun-waf (tools/liudun-waf). Do not edit by hand.');
  push(`# 上游: ${upstream}  监听: ${listen}  规则版本: ${c.version}`);
  push();
  push('# CC 限流：按客户端 IP 建限流区');
  push(`limit_req_zone $binary_remote_addr zone=waf_cc:10m rate=${ratePerSec}r/s;`);
  push();

  // 白名单 geo
  push('# 白名单 IP（命中后跳过规则与限流）');
  push('geo $waf_whitelist {');
  push('    default 0;');
  for (const ip of c.whitelist) push(`    ${ip} 1;`);
  push('}');
  push();

  // 黑名单 geo
  push('# 黑名单 IP（直接 403）');
  push('geo $waf_blacklist {');
  push('    default 0;');
  for (const ip of c.blacklist) push(`    ${ip} 1;`);
  push('}');
  push();

  // 签名 map：按类型聚合
  const byType = new Map();
  for (const sig of c.signatures) {
    if (!byType.has(sig.type)) byType.set(sig.type, []);
    byType.get(sig.type).push(sig);
  }
  for (const [type, sigs] of byType) {
    push(`# ${type} 签名规则`);
    push(`map $request_uri $waf_${type} {`);
    push('    default 0;');
    for (const sig of sigs) push(`    "~*${sig.pattern}" 1;  # ${sig.id} ${sig.reason}`);
    push('}');
    push();
  }

  push(`server {`);
  push(`    listen ${listen};`);
  push();
  push('    location / {');
  push('        # 白名单 geo 已在上游声明；nginx 侧如需白名单跳过规则，可在此用');
  push('        # if ($waf_whitelist = 1) { break; } 放行后再执行下方拦截判断。');
  push();
  push('        # 黑名单拦截');
  push('        if ($waf_blacklist = 1) { return 403; }');
  for (const type of byType.keys()) {
    push(`        if ($waf_${type} = 1) { return 403; }`);
  }
  push();
  push(`        limit_req zone=waf_cc burst=5 nodelay;`);
  push();
  push(`        proxy_pass ${upstream};`);
  push('        proxy_set_header Host $host;');
  push('        proxy_set_header X-Real-IP $remote_addr;');
  push('        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;');
  push('    }');
  push('}');

  return lines.join('\n') + '\n';
}
