/** 合规页入参：语言 + 当前子类型 */
interface LegalProps {
  locale: Locale; // 当前语言（本批文案以中文为主，英文占位后续补词典）
  kind: LegalKind; // 合规页子类型：决定渲染哪一篇骨架
} // 入参结构结束

/** 合规静态页组件：按子类型渲染标题、生效日期行与分节骨架，底部标注骨架性质 */
export function Legal({ kind }: LegalProps) {
  const doc = DOCS[kind]; // 取当前子类型对应的文档骨架
  // 子类型未登记时走空态：不白屏，提示正文待发布
  if (!doc) {
    return <EmptyState kind="set" title="内容待发布" hint="该页面正文尚未配置。" />; // 空态兜底渲染
  } // 空态分支结束
  // 跳到社区：复用路由挂载前缀，子路径部署下链接仍然正确
  function goCommunity(): void {
    navigatePath(baseOf() + 'community'); // 写地址栏并广播路由事件
  } // goCommunity 结束
  // 跳到个人中心：导出数据与注销账号都在该视图内
  function goAccount(): void {
    navigatePath(baseOf() + 'account'); // 写地址栏并广播路由事件
  } // goAccount 结束
  return (
    <article className="legal-page"> {/* 合规页根容器 */}
      {/* 页头：主标题 + 生效日期 / 更新时间行 */}
      <header className="legal-head">
        <h1>{doc.title}</h1> {/* 页面主标题 */}
        <p className="legal-meta">生效日期：待补充：法务复核后填写正式生效日期　·　最近更新：2026-11-25</p> {/* 生效日期 / 更新时间行 */}
      </header>
      {/* 分节骨架：逐节渲染标题与段落，占位行原样保留以便后续补写 */}
      {doc.sections.map((section) => (
        <section className="legal-section" key={section.heading}> {/* 单个分节 */}
          <h2>{section.heading}</h2> {/* 分节标题 */}
          {section.paragraphs.map((paragraph, index) => (
            <p key={index}>{paragraph}</p> // 单条正文段落
          ))}
        </section>
      ))}
      {/* 帮助中心直达入口：对应上方「发帖 / 导出 / 注销」小节提到的真实视图 */}
      {kind === 'help' && (
        <div className="legal-actions"> {/* 帮助中心操作行 */}
          <button type="button" className="btn primary" onClick={goCommunity}>进入社区</button> {/* 直达社区视图 */}
          <button type="button" className="btn ghost" onClick={goAccount}>前往个人中心</button> {/* 直达个人中心视图 */}
        </div>
      )}
      {/* 骨架性质显式标记：提示当前条款未经法务复核，占位项不构成承诺 */}
      <footer className="legal-note">
        本文为结构骨架，正式条款待法务复核后发布；页面中标注「待补充」的事项尚未确认，不构成承诺。
      </footer>
    </article>
  );
} // Legal 结束
